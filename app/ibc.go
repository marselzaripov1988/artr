package app

import (
	sdk "github.com/cosmos/cosmos-sdk/types"
	paramTypes "github.com/cosmos/cosmos-sdk/x/params/types"
)

// noLegacyParams — заглушка подпространства параметров для IBC.
//
// Кееперы ядра IBC и модуля переводов принимают подпространство x/params
// последним аргументом, но пользуются им в одном-единственном месте: при
// переносе параметров из старого хранилища в новое, когда сеть уже
// работала на IBC прежних версий и обновляется.
//
// У Artery такого прошлого нет — IBC подключается впервые, переносить
// нечего. А x/params из проекта выкорчеван совсем при переезде на SDK
// 0.47, и заводить его обратно ради неиспользуемого аргумента незачем.
//
// Заглушка, а не nil: nil дал бы падение по указателю, если миграция
// всё-таки будет вызвана. Пустой GetParamSet оставит структуру
// параметров нулевой, и вызывающий код возьмёт значения по умолчанию.
type noLegacyParams struct{}

func (noLegacyParams) GetParamSet(sdk.Context, paramTypes.ParamSet) {}
